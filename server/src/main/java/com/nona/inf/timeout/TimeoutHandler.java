package com.nona.inf.timeout;

/**
 * 超时处理器契约：绑定一类超时类型的到期处理行为。
 * <p>
 * 幂等契约（引擎崩溃恢复策略的前提）：fire 可能因恢复重扫被重复调用，
 * 实现必须保证重复执行与单次执行结果等价（业务侧经状态机守卫/幂等
 * 约束保证）；引擎只保证「认领成功才 fire、处理成功才清除截止时间」
 * 的编排，不承担任何业务幂等责任。处理器实现内协调各业务用例
 * （经 Spring 注入），不直接操作业务表。
 *
 * @param <T> 业务对象引用类型（与所属数据端口的候选一致）
 */
public interface TimeoutHandler<T> {

    /**
     * 本处理器服务的超时类型（类型注册与路由键）。
     *
     * @return 超时类型
     */
    TimeoutType type();

    /**
     * 执行到期处理（幂等契约，见类注释；返回值无——副作用表达于
     * 业务用例的持久化，由调用方事务统一提交/回滚）。
     *
     * @param target 到期业务对象引用
     */
    void fire(T target);
}